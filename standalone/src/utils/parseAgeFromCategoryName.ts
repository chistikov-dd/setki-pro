/**
 * Fallback-парсинг возрастного диапазона из названия категории турнира.
 *
 * Организаторы турниров на setki.pro не всегда заполняют отдельные числовые поля
 * min_age/max_age у категории — но возраст почти всегда присутствует как текст в самом
 * названии категории, в едином формате "N - M лет" (в реальных данных дефис может быть
 * как с пробелами вокруг ("10 - 11 лет"), так и без ("10-11 лет") — организаторы вводят
 * название вручную и форматируют по-разному).
 *
 * Примеры реальных названий категорий (см. tournament_68_*.json):
 *   "Девочки, 10 - 11 лет, до 27 кг [B]"       -> { min: 10, max: 11 }
 *   "Мужчины, 20 - 30 лет, до 100 кг [B]"      -> { min: 20, max: 30 }
 *   "Юниоры, 18 - 20 лет, до 66 кг [B]"        -> { min: 18, max: 20 }
 *   "Старшие юноши, 16 - 17 лет, 63-110 кг [A]" -> { min: 16, max: 17 }
 *     (обрати внимание: "63-110 кг" в этом же названии — диапазон ВЕСА без пробелов
 *     и без слова "лет" сразу после чисел, поэтому не распознаётся как возраст)
 *   "Мужчины, до 100 кг" (без возраста в названии) -> null
 */

// Узкая и специфичная регулярка: два числа, окружённые опциональными пробелами вокруг
// дефиса, сразу за которыми (после опционального пробела) идёт слово "лет". Наличие
// "лет" сразу после диапазона — ключевой отличительный признак от диапазона веса
// (веса в названиях всегда сопровождаются "кг", а не "лет").
const AGE_RANGE_PATTERN = /(\d+)\s*-\s*(\d+)\s*лет/;

export function parseAgeRangeFromCategoryName(categoryName: string | null | undefined): { min: number; max: number } | null {
  if (!categoryName) return null;

  const match = AGE_RANGE_PATTERN.exec(categoryName);
  if (!match) return null;

  const min = Number.parseInt(match[1], 10);
  const max = Number.parseInt(match[2], 10);

  if (Number.isNaN(min) || Number.isNaN(max)) return null;

  return { min, max };
}
